function cieVectorPoint([x,y],mode){
 if(mode==='xy')return{x,y};
 const divisor=-2*x+12*y+3;
 return{x:4*x/divisor,y:9*y/divisor};
}

// Keep the original, cached smooth raster interior. Its perimeter is clipped
// against the official 2 nm locus in screen coordinates on every draw, so
// zooming cannot expose the raster's old pixel-staircase alpha boundary.
function drawCieSpectrumVectorClipped(ctx,X,Y,mode,bounds){
 const image=cieSpectrumImage(mode);
 const left=X(0),top=Y(bounds.ymax),width=X(bounds.xmax)-left,height=Y(0)-top;
 if(width<=0||height<=0)return;
 ctx.save();
 ctx.beginPath();
 CIE_VECTOR_XY.forEach((point,i)=>{
  const p=cieVectorPoint(point,mode);
  if(i===0)ctx.moveTo(X(p.x),Y(p.y));else ctx.lineTo(X(p.x),Y(p.y));
 });
 ctx.closePath();
 ctx.clip();
 ctx.drawImage(image,left,top,width,height);
 ctx.restore();
}
